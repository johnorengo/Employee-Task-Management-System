BEGIN;

CREATE TABLE IF NOT EXISTS tbl_admin (
    user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fullname text NOT NULL,
    username text NOT NULL UNIQUE,
    email text NOT NULL UNIQUE,
    password text NOT NULL,
    temp_password text,
    user_role smallint NOT NULL CHECK (user_role IN (1, 2))
);

CREATE TABLE IF NOT EXISTS task_info (
    task_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    t_title text NOT NULL,
    t_description text NOT NULL DEFAULT '',
    t_start_time timestamp,
    t_end_time timestamp,
    t_user_id integer NOT NULL REFERENCES tbl_admin(user_id),
    status smallint NOT NULL DEFAULT 0 CHECK (status IN (0, 1, 2))
);

CREATE TABLE IF NOT EXISTS attendance_info (
    aten_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atn_user_id integer NOT NULL REFERENCES tbl_admin(user_id),
    in_time timestamp NOT NULL,
    out_time timestamp,
    total_duration text
);

CREATE INDEX IF NOT EXISTS task_info_user_idx ON task_info(t_user_id);
CREATE INDEX IF NOT EXISTS attendance_info_user_idx ON attendance_info(atn_user_id);

COMMIT;
